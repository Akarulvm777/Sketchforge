// Writes supabase/functions/ask/knowledge.ts: what the AI helper knows about Sketchforge, taken from the running app
// (menus + command ids, tools, tutorials, shortcuts) and the README feature notes. Run after UI changes:
//   node tools/build_knowledge.cjs        (needs Playwright, like the e2e tests)
const fs = require('fs'), path = require('path');
const H = require('./e2e/harness.cjs');
const ROOT = path.dirname(__dirname);
(async () => {
  const { pg, done } = await H.open(ROOT, 8811);
  const k = await pg.evaluate(() => {
    const SF = window.__sketchforge, strip = s => String(s || '').replace(/<[^>]+>/g, '').replace(/&[a-z]+;/g, ' ').replace(/\s+/g, ' ').trim();
    const out = [];
    out.push('## Menus and commands\nFormat: Menu › Item — command id — shortcut. Use the id in [[cmd:id|Label]].');
    for (const [menu, items] of SF.MENUS) for (const it of items) if (Array.isArray(it) && it[1]) out.push(`- ${menu} › ${it[0]} — ${it[1]}${it[2] ? ' — ' + it[2] : ''}`);
    out.push('\n## Tool palette (key in brackets) and their sub tools');
    for (const g of SF.GROUPS) out.push(`- ${g.name}${g.key ? ' [' + g.key + ']' : ''}: ${(g.subs || []).map(id => (SF.TOOLDEF[id] || {}).name || id).join(', ')}`);
    out.push('\n## Guided tutorials\nUse the id in [[tut:id|Label]].');
    for (const t of SF.TUTORIALS) {
      const steps = typeof t.steps === 'function' ? t.steps() : t.steps;
      out.push(`### ${t.title} (id: ${t.id}) — ${t.desc}\n` + steps.map(s => `- ${strip(s.t)}: ${strip(s.x)}`).join('\n'));
    }
    const help = document.querySelector('#helpBody'); if (help) { out.push('\n## Shortcuts'); help.querySelectorAll('div').forEach(d => { const a = d.querySelector('span'), b = d.querySelector('b'); if (a && b) out.push(`- ${a.textContent}: ${b.textContent}`); }); }
    return out.join('\n');
  });
  await done();
  const readme = fs.readFileSync(path.join(ROOT, 'README.md'), 'utf8');
  const feats = readme.split(/\n(?=## )/).filter(s => /^## (\d+\.\d+|Run it|What's in)/.test(s)).join('\n').replace(/`/g, "'");
  const ver = require(path.join(ROOT, 'package.json')).version;
  const text = `# Sketchforge ${ver}: knowledge\nSketchforge runs in the browser (also as a PWA on iPad / iPhone), on Windows / Mac / Linux (desktop app) and Android (app).\n\n${k}\n\n## Feature notes (from the README)\n${feats}`;
  fs.writeFileSync(path.join(ROOT, 'supabase/functions/ask/knowledge.ts'), '// Generated by tools/build_knowledge.cjs. Do not edit.\nexport const KNOWLEDGE = ' + JSON.stringify(text) + ';\n');
  console.log('knowledge:', text.length, 'chars');
})();
