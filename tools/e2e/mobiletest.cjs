const { chromium, devices } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const root = process.argv[2], out = process.argv[3];
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.svg': 'image/svg+xml', '.json': 'application/json' };
const srv = http.createServer((q, r) => { const f = path.join(root, decodeURIComponent(q.url.split('?')[0])); fs.readFile(f, (e, d) => { if (e) { r.writeHead(404); r.end(); return; } r.writeHead(200, { 'content-type': types[path.extname(f)] || 'application/octet-stream' }); r.end(d); }); }).listen(8796);
(async () => {
  const b = await chromium.launch(); const ok = [];
  const check = (n, c) => { ok.push(!!c); console.log((c ? 'ok   ' : 'FAIL ') + n); };
  const ctx = await b.newContext({ ...devices['Pixel 7'] }); const pg = await ctx.newPage(); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
  await pg.goto('http://127.0.0.1:8796/index.html'); await pg.waitForTimeout(2500);
  await pg.screenshot({ path: out + '/m_phone.png' });
  check('Menu button visible', await pg.isVisible('#btnMenu'));
  check('Panels button on screen', await pg.evaluate(() => { const r = document.querySelector('#btnDocks').getBoundingClientRect(); return r.right <= innerWidth && r.width > 0; }));
  await pg.tap('#btnMenu'); await pg.waitForTimeout(300);
  await pg.tap('#mobileMenu summary:text("Edit")'); await pg.waitForTimeout(200);
  await pg.screenshot({ path: out + '/m_menu.png' });
  await pg.tap('#mobileMenu summary:text("Layer")'); await pg.tap('#mobileMenu .mm-item:has-text("New layer")'); await pg.waitForTimeout(300);
  check('menu item runs and closes the menu', (await pg.evaluate(() => window.__sketchforge.state.layers.length)) === 3 && await pg.evaluate(() => document.querySelector('#mobileMenu').hidden));
  await pg.tap('#btnDocks'); await pg.waitForTimeout(300); await pg.screenshot({ path: out + '/m_panel1.png' });
  check('Panels 1: tool settings sheet', await pg.isVisible('#leftdock') && !(await pg.isVisible('#rightdock')));
  await pg.tap('#btnDocks'); await pg.waitForTimeout(300); await pg.screenshot({ path: out + '/m_panel2.png' });
  check('Panels 2: layers sheet', await pg.isVisible('#rightdock') && !(await pg.isVisible('#leftdock')));
  await pg.tap('#btnDocks'); await pg.waitForTimeout(300);
  check('Panels 3: closed', !(await pg.isVisible('#rightdock')) && !(await pg.isVisible('#leftdock')));
  const ip = await (await b.newContext({ ...devices['iPad Pro 11'] })).newPage(); await ip.goto('http://127.0.0.1:8796/index.html'); await ip.waitForTimeout(2500);
  await ip.screenshot({ path: out + '/m_ipad.png' });
  check('iPad portrait: no wrapped menu labels (menu button used)', await ip.isVisible('#btnMenu'));
  console.log(errs.length ? errs : 'no errors', ok.every(Boolean) ? 'PASS' : 'FAIL');
  await b.close(); srv.close();
})();
