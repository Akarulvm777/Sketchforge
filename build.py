#!/usr/bin/env python3
"""Concatenate parts/p*.js (sorted by filename) into app.js, then syntax-check with node."""
import glob, os, subprocess, sys
root = os.path.dirname(os.path.abspath(__file__))
parts = sorted(glob.glob(os.path.join(root, 'parts', 'p*.js')))
if not parts:
    sys.exit('no parts found in parts/')
import json
version = json.load(open(os.path.join(root, 'package.json'), encoding='utf-8'))['version']
# this version's notes (README sections "## X.Y: title" with "- " items) for the What's new popup
import re
mm = '.'.join(version.split('.')[:2])
readme = open(os.path.join(root, 'README.md'), encoding='utf-8').read()
changes = []
for sec in re.split(r'\n(?=## )', readme):
    if sec.startswith('## ' + mm + ':'):
        lines = sec.split('\n')
        changes.append({'title': lines[0][len(mm) + 4:].strip(), 'items': [l[2:].replace('**', '').strip() for l in lines[1:] if l.startswith('- ')]})
src = f"/* Generated by build.py from parts/*.js. Do not edit. */\nconst APP_VERSION = '{version}';\nconst APP_CHANGES = {json.dumps(changes, ensure_ascii=False)};\n" + '\n'.join(open(p, encoding='utf-8').read() for p in parts)
out = os.path.join(root, 'app.js')
open(out, 'w', encoding='utf-8', newline='\n').write(src)
print('built', len(src), 'bytes from', [os.path.basename(p) for p in parts])
r = subprocess.run(['node', '--check', out], capture_output=True, text=True)
print(r.stderr or 'syntax OK')
sys.exit(r.returncode)
