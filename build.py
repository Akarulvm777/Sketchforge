#!/usr/bin/env python3
"""Concatenate parts/p*.js (sorted by filename) into app.js, then syntax-check with node."""
import glob, os, subprocess, sys
root = os.path.dirname(os.path.abspath(__file__))
parts = sorted(glob.glob(os.path.join(root, 'parts', 'p*.js')))
if not parts:
    sys.exit('no parts found in parts/')
import json
version = json.load(open(os.path.join(root, 'package.json'), encoding='utf-8'))['version']
# this version's notes (README sections "## X.Y: title" with "- " items) for the What's new popup
import re
mm = '.'.join(version.split('.')[:2])
readme = open(os.path.join(root, 'README.md'), encoding='utf-8').read()
changes = []
for sec in re.split(r'\n(?=## )', readme):
    if sec.startswith('## ' + mm + ':'):
        lines = sec.split('\n')
        changes.append({'title': lines[0][len(mm) + 4:].strip(), 'items': [l[2:].replace('**', '').strip() for l in lines[1:] if l.startswith('- ')]})
# every version's notes, newest first, with the date and time each version first appeared (git history of package.json,
# kept in release-dates.json so builds without the git history still have them) -> the update history in What's new
from datetime import datetime, timezone
dates_file = os.path.join(root, 'release-dates.json')
try: vdates = json.load(open(dates_file, encoding='utf-8'))
except Exception: vdates = {}
try:
    log = subprocess.run(['git', 'log', '--format=%H %cI', '--', 'package.json'], cwd=root, capture_output=True, text=True).stdout.split('\n')
    for line in log:
        if not line.strip(): continue
        h, when = line.split(' ', 1)
        try: v = json.loads(subprocess.run(['git', 'show', h + ':package.json'], cwd=root, capture_output=True, text=True).stdout)['version']
        except Exception: continue
        if v not in vdates or when < vdates[v]: vdates[v] = when
except Exception: pass
if version not in vdates: vdates[version] = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
open(dates_file, 'w', encoding='utf-8', newline='\n').write(json.dumps(dict(sorted(vdates.items(), key=lambda kv: [int(x) for x in kv[0].split('.')], reverse=True)), indent=1) + '\n')
vkey = lambda v: [int(x) for x in v.split('.')]
groups = {}
for sec in re.split(r'\n(?=## )', readme):
    m = re.match(r'## (\d+\.\d+(?:\.\d+)?):\s*(.*)', sec)
    if not m: continue
    lines = sec.split('\n')
    groups.setdefault(m.group(1), []).append({'title': m.group(2).strip(), 'items': [l[2:].replace('**', '').strip() for l in lines[1:] if l.startswith('- ')]})
history = []
for k in sorted(groups, key=vkey, reverse=True):
    vs = sorted([v for v in vdates if v == k or v.startswith(k + '.')], key=vkey)
    history.append({'v': k, 'latest': vs[-1] if vs else k, 'first': vdates[vs[0]] if vs else None, 'last': vdates[vs[-1]] if vs else None, 'sections': groups[k]})
src = f"/* Generated by build.py from parts/*.js. Do not edit. */\nconst APP_VERSION = '{version}';\nconst APP_CHANGES = {json.dumps(changes, ensure_ascii=False)};\nconst APP_HISTORY = {json.dumps(history, ensure_ascii=False)};\n" + '\n'.join(open(p, encoding='utf-8').read() for p in parts)
out = os.path.join(root, 'app.js')
open(out, 'w', encoding='utf-8', newline='\n').write(src)
print('built', len(src), 'bytes from', [os.path.basename(p) for p in parts])
r = subprocess.run(['node', '--check', out], capture_output=True, text=True)
print(r.stderr or 'syntax OK')
sys.exit(r.returncode)
